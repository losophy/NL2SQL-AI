DROP TABLE IF EXISTS dim_date;
CREATE TABLE dim_date
(
    date_id INT PRIMARY KEY,
    year    INT,
    quarter VARCHAR(2),
    month   INT,
    day     INT
);

INSERT INTO dim_date (date_id, year, quarter, month, day)
WITH RECURSIVE seq (d) AS (
    SELECT DATE('2025-01-01')
    UNION ALL
    SELECT DATE_ADD(d, INTERVAL 1 DAY) FROM seq WHERE d < DATE('2025-03-31')
)
SELECT DATE_FORMAT(d, '%Y%m%d') AS date_id,
       YEAR(d)                  AS year,
       CONCAT('Q', QUARTER(d))  AS quarter,
       MONTH(d)                 AS month,
       DAY(d)                   AS day
FROM seq;


